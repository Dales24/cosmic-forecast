"""Publish a trained model to a Hugging Face repository.

Owns everything about *what* gets published — which artifacts exist, whether
they are fit to publish, and the model card that goes with them. The CLI wiring
(arguments, exit codes) lives in ``scripts/publish_model.py``.

``huggingface_hub`` is an optional dependency: importing this module never
requires it, so the rest of the app is unaffected if it isn't installed.
Authentication comes from the ``HF_TOKEN`` environment variable — never the repo.
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

from app.object_classes import NUM_CLASSES

TOKEN_ENV_VAR = "HF_TOKEN"
MODEL_FILENAME = "model.keras"
CARD_FILENAME = "README.md"


@dataclass(frozen=True)
class PublishableModel:
    """One model this project can publish, and the honest story about it."""

    key: str
    title: str
    module: str  # the app/ file that defines and trains it
    directory: Path
    task: str
    summary: str
    # Caveats that must appear on the model card. Publishing a model without
    # stating these would misrepresent what it does.
    caveats: tuple[str, ...]


PUBLISHABLE_MODELS: dict[str, PublishableModel] = {
    "classifier": PublishableModel(
        key="classifier",
        title="Cosmic Forecast — Object Classifier",
        module="app/object_classifier.py",
        directory=Path("models/object_classifier"),
        task="image-classification",
        summary=(
            f"A small convolutional network that sorts telescope image patches "
            f"into {NUM_CLASSES} object classes (satellites, galaxies, comets, "
            f"and so on)."
        ),
        caveats=(
            "Trained on **synthetic** image patches generated by "
            "`app/object_classifier.py`, not real telescope imagery. Treat its "
            "output as illustrative unless it was retrained on a real labelled "
            "dataset.",
            "The in-app `/api/classify/{id}` endpoint classifies a randomly "
            "generated patch seeded by object id — it is not analysing an "
            "actual observation of that object.",
        ),
    ),
    "trajectory": PublishableModel(
        key="trajectory",
        title="Cosmic Forecast — Trajectory Transformer",
        module="app/trajectory_transformer.py",
        directory=Path("models/trajectory_transformer"),
        task="time-series-forecasting",
        summary=(
            "A transformer that extrapolates an object's future positions from "
            "a short history of tracked coordinates."
        ),
        caveats=(
            "Trained on synthetic linear-motion tracks. It has not been "
            "validated against real orbital ephemerides.",
            "Predictions are in the app's normalised scene coordinates, not "
            "kilometres or a standard reference frame.",
        ),
    ),
}


def get_model(key: str) -> PublishableModel:
    """Look up a publishable model, failing with the valid options listed."""
    try:
        return PUBLISHABLE_MODELS[key]
    except KeyError:
        options = ", ".join(sorted(PUBLISHABLE_MODELS))
        raise ValueError(f"Unknown model {key!r}. Choose one of: {options}") from None


def model_artifact(model: PublishableModel, root: str | Path = ".") -> Path:
    """The saved weights for `model`, or a clear error if training never ran."""
    path = Path(root) / model.directory / MODEL_FILENAME
    if not path.is_file():
        raise FileNotFoundError(
            f"No trained {model.key} model at {path}. Train and save one first "
            f"(see README 'Training')."
        )
    return path


def resolve_token(explicit: str | None = None) -> str:
    """The Hugging Face write token, from the argument or the environment."""
    token = explicit or os.environ.get(TOKEN_ENV_VAR, "")
    if not token.strip():
        raise ValueError(
            f"No Hugging Face token. Set {TOKEN_ENV_VAR} in your environment "
            f"(never commit it) or pass --token."
        )
    return token.strip()


def build_model_card(model: PublishableModel, repo_id: str, at: datetime) -> str:
    """The README that ships beside the weights.

    Hugging Face renders this as the model card, so the caveats belong here and
    not only in our own docs — this is the only description most people see.
    """
    caveats = "\n".join(f"- {line}" for line in model.caveats)
    return f"""---
library_name: keras
pipeline_tag: {model.task}
tags:
  - astronomy
  - cosmic-forecast
---

# {model.title}

{model.summary}

## Limitations

{caveats}

## Usage

```python
from huggingface_hub import hf_hub_download
import tensorflow as tf

path = hf_hub_download("{repo_id}", "{MODEL_FILENAME}")
model = tf.keras.models.load_model(path)
```

## Source

Produced by [Cosmic Forecast](https://github.com/) — see `{model.module}`
in the project repository for the architecture and training code.

Published {at.strftime('%Y-%m-%d')}.
"""


@dataclass(frozen=True)
class PublishPlan:
    """What a publish run would upload. Returned by a dry run unchanged."""

    repo_id: str
    model_key: str
    artifact: Path
    card: str
    uploaded: bool


def publish_model(
    model_key: str,
    repo_id: str,
    token: str | None = None,
    root: str | Path = ".",
    private: bool = True,
    dry_run: bool = False,
    now: datetime | None = None,
) -> PublishPlan:
    """Upload a trained model plus its card to `repo_id`.

    Everything is validated before anything is sent, so a missing artifact or
    token fails without leaving a half-created repository. `dry_run` builds the
    same plan and uploads nothing. Repos are created **private** by default —
    making one public should be a deliberate act, not a default.
    """
    model = get_model(model_key)
    artifact = model_artifact(model, root)
    card = build_model_card(model, repo_id, now or datetime.now(timezone.utc))

    if dry_run:
        return PublishPlan(repo_id, model.key, artifact, card, uploaded=False)

    resolved_token = resolve_token(token)
    api = _hub_api(resolved_token)
    api.create_repo(repo_id=repo_id, repo_type="model", private=private, exist_ok=True)
    api.upload_file(
        path_or_fileobj=str(artifact),
        path_in_repo=MODEL_FILENAME,
        repo_id=repo_id,
        repo_type="model",
    )
    api.upload_file(
        path_or_fileobj=card.encode("utf-8"),
        path_in_repo=CARD_FILENAME,
        repo_id=repo_id,
        repo_type="model",
    )
    return PublishPlan(repo_id, model.key, artifact, card, uploaded=True)


def _hub_api(token: str):
    """The Hugging Face client, imported here so the dep stays optional."""
    try:
        from huggingface_hub import HfApi
    except ImportError:
        raise ImportError(
            "huggingface_hub is not installed. Add it with: "
            "uv add --group publish huggingface_hub"
        ) from None
    return HfApi(token=token)
